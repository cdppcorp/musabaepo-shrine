function G(y0, rows) {
  const out = Array.from({ length: H }, () => '.'.repeat(W))
  rows.forEach((r, i) => {
    if (r.length !== W) throw new Error(`hair.js: y${y0 + i} 길이 ${r.length}: ${r}`)
    out[y0 + i] = r.replace(/S/g, 'h')
  })
  return out
}
