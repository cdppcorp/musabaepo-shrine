/** look → 재료 키 색 사전 (+ 각 모듈의 고정 대문자 색은 합성기가 덧붙임) */
export function paletteOf(look) {
  const sp = SPECIES_KEYS[look[0]] ?? 'human'
  const skin = SKIN[sp][look[1]] ?? SKIN[sp][0]
  const [, d, c, h, f, g] = skin
  const [a, z, b, x] = HAIR[look[5]]?.[1] ?? HAIR[0][1]
  const [l, j, i, k] = TOP[look[7]]?.[1] ?? TOP[0][1]
  const [s, o, n, m] = BOTTOM[look[9]]?.[1] ?? BOTTOM[0][1]
  const shoe = SHOES[look[10]]?.[1] ?? [d, d, c, h]
  const [tt, p, q, r] = shoe
  return {
    a, z, b, x, d, c, h, f, g,
    e: EYE_DARK, y: EYES[look[3]]?.[1] ?? EYES[0][1], w: EYE_LIGHT,
    l, j, i, k, s, o, n, m, t: tt, p, q, r,
  }
}
